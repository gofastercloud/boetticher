package ansible

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"sort"
	"strings"

	"github.com/dave/labinabox/internal/model"
)

func Inventory(s model.Site) (string, error) {
	if err := s.Validate(); err != nil {
		return "", err
	}
	modules := append([]model.Module(nil), s.Modules...)
	sort.Slice(modules, func(i, j int) bool { return modules[i].Name < modules[j].Name })
	var b strings.Builder
	b.WriteString("# Generated by Lab-in-a-Box. Do not edit.\n")
	b.WriteString("# Model revision: ")
	revision, err := s.Revision()
	if err != nil {
		return "", err
	}
	b.WriteString(revision + "\n\n")
	b.WriteString("[proxmox]\n")
	for _, module := range modules {
		if module.Name == "lab-proxmox-01" {
			writeHost(&b, module, false)
		}
	}
	b.WriteString("\n[dns]\n")
	for _, module := range modules {
		if module.Role == "DNS/NTP" {
			writeHost(&b, module, true)
		}
	}
	b.WriteString("\n[monitor]\n")
	for _, module := range modules {
		if module.Name == "lab-monitor-01" {
			writeHost(&b, module, true)
		}
	}
	b.WriteString("\n[portal]\n")
	for _, module := range modules {
		if module.Name == "lab-portal-01" {
			writeHost(&b, module, true)
		}
	}
	b.WriteString("\n[managed:children]\nproxmox\ndns\nmonitor\nportal\n\n")
	b.WriteString("[managed:vars]\nansible_connection=ssh\nansible_python_interpreter=/usr/bin/python3\nansible_host_key_checking=true\n")
	return b.String(), nil
}

func writeHost(b *strings.Builder, module model.Module, throughBastion bool) {
	user := module.SSHUser
	if user == "" {
		user = model.DefaultAdminSSHUser
	}
	fmt.Fprintf(b, "%s ansible_host=%s ansible_user=%s", module.Name, module.Address, user)
	if throughBastion {
		fmt.Fprintf(b, " ansible_ssh_common_args='-o ProxyJump=lab-bastion -o HostKeyAlias=%s.%s'", module.Hostname, model.DefaultDomain)
	} else {
		fmt.Fprintf(b, " ansible_ssh_common_args='-o HostKeyAlias=%s.%s'", module.Hostname, model.DefaultDomain)
	}
	b.WriteByte('\n')
}

func Variables(s model.Site) ([]byte, error) {
	if err := s.Validate(); err != nil {
		return nil, err
	}
	revision, err := s.Revision()
	if err != nil {
		return nil, err
	}
	value := struct {
		ModelRevision string `json:"model_revision"`
		Domain        string `json:"domain"`
		IPv4Only      bool   `json:"ipv4_only"`
	}{revision, s.Network.Domain, true}
	data, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// Run executes ansible-playbook with model variables over stdin. This keeps
// the invocation free of secret values and avoids a plaintext extra-vars
// file. The playbook itself must obtain any future secret material through an
// approved runtime mechanism.
func Run(ctx context.Context, playbook, inventory string, variables []byte) error {
	if playbook == "" || inventory == "" {
		return errors.New("Ansible playbook and inventory are required")
	}
	executable, err := exec.LookPath("ansible-playbook")
	if err != nil {
		return fmt.Errorf("ansible-playbook is required: %w", err)
	}
	command := exec.CommandContext(ctx, executable, "-i", inventory, playbook, "--extra-vars", "@-")
	command.Stdin = strings.NewReader(string(variables))
	command.Env = append(os.Environ(), "ANSIBLE_HOST_KEY_CHECKING=True")
	if _, err := command.CombinedOutput(); err != nil {
		return fmt.Errorf("ansible-playbook failed: %w", err)
	}
	return nil
}
